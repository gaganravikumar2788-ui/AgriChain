export function getLocalizedAgrometAdvisory(w, lang = 'en') {
  if (!w) return null;
  const condition = (w.condition || '').toLowerCase();
  const temp = w.temperature;

  let key = 'favorable';
  let badgeColor = 'bg-green-100 text-green-800 border-green-300';
  let cardBg = 'bg-green-50/70 border-green-200';
  let icon = '🌾';

  if (condition.includes('rain') || condition.includes('drizzle') || condition.includes('thunder') || w.precipitationProb > 45) {
    key = 'precipitation';
    badgeColor = 'bg-blue-100 text-blue-800 border-blue-300';
    cardBg = 'bg-blue-50/70 border-blue-200';
    icon = '🌧️';
  } else if (temp >= 33) {
    key = 'heat';
    badgeColor = 'bg-amber-100 text-amber-800 border-amber-300';
    cardBg = 'bg-amber-50/70 border-amber-200';
    icon = '☀️';
  } else if (w.humidity >= 75) {
    key = 'humidity';
    badgeColor = 'bg-emerald-100 text-emerald-800 border-emerald-300';
    cardBg = 'bg-emerald-50/70 border-emerald-200';
    icon = '🌱';
  }

  const adv = AGROMET_ADVISORIES[key];
  return {
    key,
    icon,
    badgeColor,
    cardBg,
    type: adv.type[lang] || adv.type.en,
    title: adv.title[lang] || adv.title.en,
    advice: adv.advice[lang] || adv.advice.en,
    irrigation: adv.irrigation[lang] || adv.irrigation.en,
    spray: adv.spray[lang] || adv.spray.en,
    harvest: adv.harvest[lang] || adv.harvest.en
  };
}
